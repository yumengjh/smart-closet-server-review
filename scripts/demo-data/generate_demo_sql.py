#!/usr/bin/env python3
"""Generate demonstration activity for the management dashboard (docs/design/2026-10-21-大屏演示数据与布局设计.md).

Every generated row belongs to an account whose username starts with ``demo_`` so it can be removed with
``cleanup_demo.sql``. Garments are copies of existing real garments (same image assets, recognition result and
derived indexes), so no background task recomputes anything and no model is called. Run against a stopped server:

    python3 scripts/demo-data/generate_demo_sql.py --users 360 --days 60 > /tmp/demo.sql
    java -cp h2.jar org.h2.tools.RunScript -url jdbc:h2:file:data/db/closet -user sa -script /tmp/demo.sql
"""
import argparse
import datetime as dt
import json
import random
import sys
import uuid
from zoneinfo import ZoneInfo

ZONE = ZoneInfo("Asia/Shanghai")
SURNAMES = "林陈王李张刘杨黄赵周吴徐孙胡朱高何郭马罗梁宋郑谢韩唐冯于董萧程曹袁邓许傅沈曾彭吕苏卢蒋蔡贾丁魏薛叶阎余潘杜戴夏钟汪田任姜范方石姚谭廖邹熊金陆郝孔白崔康毛邱秦江史顾侯邵孟龙万段雷钱汤尹黎易常武乔贺赖龚文"
GIVEN = ["小鱼", "鹿鹿", "一一", "朵朵", "星河", "南风", "晚晚", "柚子", "木木", "可可", "糖糖", "安安", "知夏", "初秋", "暖暖",
         "七七", "阿桃", "小满", "清禾", "若溪", "予安", "一诺", "嘉禾", "沐沐", "芒果", "栗子", "西西", "小葵", "半夏", "云朵"]
OUTFIT_NAMES = ["通勤 · 周一", "周末出街", "约会穿搭", "雨天也好看", "办公室休闲", "短途旅行", "看展日", "健身房", "露营", "面试正装",
                "早春叠穿", "极简黑白", "多巴胺配色", "法式慵懒", "学院风", "城市漫步", "居家舒适", "咖啡店", "音乐节", "家庭聚会"]
HOUR_WEIGHTS = [1, 0.5, 0.3, 0.2, 0.2, 0.4, 1.5, 4, 6, 4, 3, 4, 7, 6, 3, 3, 3.5, 4, 5, 7, 9, 10, 8, 4]
BCRYPT_CHARS = "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"


def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def ms(moment: dt.datetime) -> int:
    return int(moment.timestamp() * 1000)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--users", type=int, default=360)
    parser.add_argument("--days", type=int, default=60)
    parser.add_argument("--seed", type=int, default=20261021)
    parser.add_argument("--sources", type=int, default=270, help="number of real active garments available to copy")
    parser.add_argument("--now-ms", type=int, default=None, help="generate up to this instant (default: now)")
    args = parser.parse_args()
    rnd = random.Random(args.seed)
    now = dt.datetime.fromtimestamp((args.now_ms or ms(dt.datetime.now(ZONE))) / 1000, ZONE)
    start = (now - dt.timedelta(days=args.days)).replace(hour=0, minute=0, second=0, microsecond=0)
    out = sys.stdout
    w = lambda line: out.write(line + "\n")

    w("-- Generated by scripts/demo-data/generate_demo_sql.py; remove with cleanup_demo.sql")
    w("SET AUTOCOMMIT FALSE;")
    w("CREATE LOCAL TEMPORARY TABLE demo_src AS SELECT ROW_NUMBER() OVER (ORDER BY created_at_ms, id) rn, id, source_asset_id, display_asset_id, source_origin,"
      " automatic_json, overrides_json, revision, name FROM garment WHERE closet_status='ACTIVE' AND owner_username IS NOT NULL AND owner_username NOT LIKE 'demo\\_%' ESCAPE '\\';")
    w("CREATE LOCAL TEMPORARY TABLE demo_outfit_src AS SELECT ROW_NUMBER() OVER (ORDER BY created_at_ms, id) rn, scene_version, scene_json FROM outfit WHERE owner_username NOT LIKE 'demo\\_%' ESCAPE '\\';")

    def moment_on(day: dt.date, earliest: dt.datetime | None = None) -> dt.datetime | None:
        hours = list(range(24))
        weights = HOUR_WEIGHTS[:]
        for _ in range(8):
            hour = rnd.choices(hours, weights)[0]
            moment = dt.datetime(day.year, day.month, day.day, hour, rnd.randrange(60), rnd.randrange(60), tzinfo=ZONE)
            if moment <= now and (earliest is None or moment >= earliest):
                return moment
        return None

    total_days = (now.date() - start.date()).days + 1
    garment_rows = outfit_rows = log_rows = 0
    for index in range(args.users):
        # Sign-ups accelerate towards the present (launch growth), with a little noise.
        position = (rnd.random() ** 0.62)
        signed = start + dt.timedelta(days=position * (total_days - 0.2), hours=rnd.uniform(0, 1))
        signed = signed.replace(hour=rnd.choices(range(24), HOUR_WEIGHTS)[0], minute=rnd.randrange(60))
        if signed > now:
            signed = now - dt.timedelta(minutes=rnd.randrange(5, 600))
        username = f"demo_{index + 1:04d}"
        display = rnd.choice(SURNAMES) + rnd.choice(GIVEN) if rnd.random() < 0.8 else None
        via = rnd.choices(["INVITE", "OPEN", "ADMIN"], [0.58, 0.32, 0.10])[0]
        password = "$2a$12$" + "".join(rnd.choice(BCRYPT_CHARS) for _ in range(53))
        level = rnd.paretovariate(1.6)  # a few heavy users, many light ones
        daily_p = min(0.85, 0.12 + 0.11 * level)
        active_days = []
        day = signed.date()
        while day <= now.date():
            weekend = day.weekday() >= 5
            if day == signed.date() or rnd.random() < daily_p * (1.25 if weekend else 1.0):
                active_days.append(day)
            day += dt.timedelta(days=1)
        last_seen = None

        # Garments: an onboarding burst, then a trickle on active days.
        wardrobe_size = max(3, min(70, int(rnd.lognormvariate(2.9, 0.65))))
        sources = rnd.sample(range(1, args.sources + 1), min(wardrobe_size, args.sources))
        garments = []
        for n, source in enumerate(sources):
            if n < wardrobe_size * 0.6 or len(active_days) == 1:
                moment = signed + dt.timedelta(minutes=rnd.randrange(2, 240))
            else:
                moment = moment_on(rnd.choice(active_days), signed)
            if moment is None or moment > now:
                moment = signed + dt.timedelta(minutes=rnd.randrange(2, 60))
            if moment > now:
                continue
            status = rnd.choices(["ACTIVE", "DRAFT", "TRASHED"], [0.88, 0.08, 0.04])[0]
            garments.append((str(uuid.uuid4()), source, moment, status))
        garments.sort(key=lambda g: g[2])

        w(f"INSERT INTO closet_user(username,password_hash,role,must_change_password,enabled,created_at_ms,display_name,last_login_at_ms,registered_via) VALUES("
          f"{q(username)},{q(password)},'USER',0,1,{ms(signed)},{q(display)},NULL,{q(via)});")
        w(f"INSERT INTO account_event(id,occurred_at_ms,username,actor,action,detail) VALUES({q(str(uuid.uuid4()))},{ms(signed)},{q(username)},{q(username)},'REGISTERED',{q('via=' + via)});")
        fit_choice = lambda: rnd.choices(["女款", "男款", "中性"], [0.5, 0.28, 0.22])[0]
        for gid, source, moment, status in garments:
            fit = json.dumps({"genderFit": [fit_choice()]}, ensure_ascii=False)
            w("INSERT INTO garment(id,source_asset_id,display_asset_id,source_origin,automatic_json,overrides_json,display_user_selected,revision,created_at_ms,updated_at_ms,"
              "owner_username,closet_status,restore_status,name,favorite) SELECT "
              f"{q(gid)},source_asset_id,display_asset_id,source_origin,automatic_json,"
              f"CASE WHEN automatic_json LIKE '%\"genderFit\"%' THEN overrides_json ELSE {q(fit)} END,0,revision,{ms(moment)},{ms(moment)},"
              f"{q(username)},{q(status)},{q('ACTIVE' if status == 'TRASHED' else None)},name,{q(rnd.random() < 0.12)} FROM demo_src WHERE rn={source};")
            for table, cols in [
                ("garment_color", "display_asset_id,palette_json,algorithm,updated_at_ms"),
                ("garment_visual", "display_asset_id,algorithm,phash,mask_grid,aspect,palette_json,updated_at_ms"),
                ("garment_image_embedding", "display_asset_id,model_version,vector,updated_at_ms"),
                ("garment_image_style", "display_asset_id,style,source,evidence,updated_at_ms"),
                ("garment_duplicate_check", "display_asset_id,found,checked_at_ms"),
                ("garment_embedding", "model_version,garment_revision,card_hash,card_text,vector,updated_at_ms"),
            ]:
                w(f"INSERT INTO {table}(garment_id,owner_username,{cols}) SELECT {q(gid)},{q(username)},{cols.replace('found', '0')} FROM {table} t"
                  f" WHERE t.garment_id=(SELECT id FROM demo_src WHERE rn={source});")
            garment_rows += 1
            w(f"INSERT INTO model_usage(id,owner_username,feature,model,input_tokens,output_tokens,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},"
              f"'RECOGNITION','gpt-6-luna',{rnd.randint(1800, 4200)},{rnd.randint(300, 900)},{ms(moment)});")
        active_ids = [g[0] for g in garments if g[3] == "ACTIVE"]

        quota_image, quota_agent = {}, {}
        for gid, _, moment, _ in garments:
            quota_image[moment.date()] = quota_image.get(moment.date(), 0) + 1

        outfits = []
        for day in active_days:
            sessions = 1 + int(rnd.random() < 0.35 * min(level, 3))
            for _ in range(sessions):
                moment = moment_on(day, signed)
                if moment is None:
                    continue
                last_seen = max(last_seen or moment, moment)
                w(f"INSERT INTO account_event(id,occurred_at_ms,username,actor,action,detail) VALUES({q(str(uuid.uuid4()))},{ms(moment)},{q(username)},{q(username)},'LOGIN_SUCCEEDED',NULL);")
                if len(active_ids) < 3:
                    continue
                # A recommendation run shows 3 combinations; some get liked, opened, swapped or worn.
                for _run in range(rnd.choices([0, 1, 2, 3], [0.15, 0.5, 0.25, 0.1])[0]):
                    run_id = str(uuid.uuid4())
                    source = rnd.choices(["PAGE", "MORE", "AGENT", "INSPIRATION", "SWAP"], [0.42, 0.24, 0.16, 0.14, 0.04])[0]
                    at = moment + dt.timedelta(seconds=rnd.randrange(5, 900))
                    if at > now:
                        at = moment
                    for rank in range(1, 4):
                        log_id = str(uuid.uuid4())
                        items = rnd.sample(active_ids, min(len(active_ids), rnd.choice([2, 3, 3, 4])))
                        w("INSERT INTO recommendation_log(id,run_id,owner_username,source,intent_json,outfit_key,garment_ids_json,rank_no,total_score,score_vector_json,tags_json,rule_version,created_at_ms) VALUES("
                          f"{q(log_id)},{q(run_id)},{q(username)},{q(source)},'{{}}',{q('demo-' + log_id[:12])},{q(json.dumps(items))},{rank},{round(rnd.uniform(0.55, 0.96), 3)},'{{}}','[]','demo',{ms(at)});")
                        log_rows += 1
                        roll = rnd.random()
                        later = at + dt.timedelta(seconds=rnd.randrange(10, 400))
                        if later > now:
                            later = at
                        if roll < 0.10:
                            w(f"INSERT INTO recommendation_feedback(id,log_id,owner_username,verdict,reasons_json,garment_id,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(log_id)},{q(username)},'UP','[]',NULL,{ms(later)});")
                        elif roll < 0.14:
                            w(f"INSERT INTO recommendation_feedback(id,log_id,owner_username,verdict,reasons_json,garment_id,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(log_id)},{q(username)},'DOWN','[]',NULL,{ms(later)});")
                        if rnd.random() < 0.09:
                            w(f"INSERT INTO style_signal(id,owner_username,kind,log_id,garment_id,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},'OPEN_WORKSPACE',{q(log_id)},NULL,{ms(later)});")
                        if rnd.random() < 0.22:
                            w(f"INSERT INTO style_signal(id,owner_username,kind,log_id,garment_id,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},'VIEW_DETAIL',{q(log_id)},{q(items[0])},{ms(later)});")
                        if rnd.random() < 0.03:
                            w(f"INSERT INTO style_signal(id,owner_username,kind,log_id,garment_id,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},'SWAP_OUT',{q(log_id)},{q(items[-1])},{ms(later)});")
                        if rnd.random() < 0.05:
                            worn = later + dt.timedelta(hours=rnd.randrange(1, 60))
                            if worn <= now:
                                w(f"INSERT INTO wear_log(id,owner_username,outfit_id,garment_ids_json,worn_on,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},NULL,"
                                  f"{q(json.dumps(items))},{q(worn.date().isoformat())},{ms(worn)});")
                # Saved outfits, everyday wear logs and assistant use.
                if rnd.random() < 0.18:
                    oid = str(uuid.uuid4())
                    at = moment + dt.timedelta(minutes=rnd.randrange(1, 30))
                    at = min(at, now)
                    w(f"INSERT INTO outfit(id,owner_username,name,scene_version,scene_json,revision,created_at_ms,updated_at_ms) SELECT {q(oid)},{q(username)},"
                      f"{q(rnd.choice(OUTFIT_NAMES))},scene_version,scene_json,1,{ms(at)},{ms(at)} FROM demo_outfit_src WHERE rn={rnd.randint(1, 6)};")
                    outfits.append(oid)
                    outfit_rows += 1
                if rnd.random() < 0.22:
                    items = rnd.sample(active_ids, min(len(active_ids), 3))
                    at = min(moment + dt.timedelta(minutes=rnd.randrange(1, 90)), now)
                    w(f"INSERT INTO wear_log(id,owner_username,outfit_id,garment_ids_json,worn_on,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},"
                      f"{q(rnd.choice(outfits)) if outfits and rnd.random() < 0.5 else 'NULL'},{q(json.dumps(items))},{q(day.isoformat())},{ms(at)});")
                if rnd.random() < 0.3:
                    messages = rnd.randint(1, 8)
                    quota_agent[day] = quota_agent.get(day, 0) + messages
                    for _m in range(messages):
                        at = min(moment + dt.timedelta(seconds=rnd.randrange(10, 1800)), now)
                        w(f"INSERT INTO model_usage(id,owner_username,feature,model,input_tokens,output_tokens,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},"
                          f"'AGENT','gpt-6-luna',{rnd.randint(6000, 24000)},{rnd.randint(200, 1400)},{ms(at)});")
                if rnd.random() < 0.04:
                    at = min(moment + dt.timedelta(minutes=rnd.randrange(1, 20)), now)
                    w(f"INSERT INTO model_usage(id,owner_username,feature,model,input_tokens,output_tokens,created_at_ms) VALUES({q(str(uuid.uuid4()))},{q(username)},"
                      f"'OOTD_EXTRACT','gpt-6-luna',{rnd.randint(4000, 7000)},{rnd.randint(300, 800)},{ms(at)});")
                    quota_image[day] = quota_image.get(day, 0) + 1
        for day, used in quota_image.items():
            w(f"INSERT INTO ai_daily_quota(owner_username,quota_date,used) VALUES({q(username)},{q(day.isoformat())},{min(used, 999)});")
        for day, used in quota_agent.items():
            w(f"INSERT INTO agent_daily_quota(owner_username,quota_date,used) VALUES({q(username)},{q(day.isoformat())},{min(used, 999)});")
        w(f"UPDATE closet_user SET last_login_at_ms={ms(last_seen or signed)} WHERE username={q(username)};")
        if index % 20 == 19:
            w("COMMIT;")
    w("DROP TABLE demo_src; DROP TABLE demo_outfit_src;")
    w("COMMIT;")
    print(f"-- users={args.users} garments={garment_rows} outfits={outfit_rows} recommendations={log_rows}", file=sys.stderr)


if __name__ == "__main__":
    main()
